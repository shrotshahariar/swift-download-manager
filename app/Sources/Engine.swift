import Foundation

/// Launches and owns the bundled aria2c process.
final class Engine {
    private var process: Process?
    private(set) var lastError: String?

    static let supportDir: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let dir = base.appendingPathComponent("SwiftDM", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()
    static var confURL: URL { supportDir.appendingPathComponent("aria2.conf") }
    static var sessionURL: URL { supportDir.appendingPathComponent("aria2.session") }
    static var logURL: URL { supportDir.appendingPathComponent("aria2.log") }

    var isRunning: Bool { process?.isRunning ?? false }

    private var binary: URL? {
        if let b = Bundle.main.url(forResource: "aria2c", withExtension: nil) { return b }
        let motrix = URL(fileURLWithPath: "/Applications/Motrix.app/Contents/Resources/extra/darwin/arm64/aria2c")
        return FileManager.default.isExecutableFile(atPath: motrix.path) ? motrix : nil
    }

    private func writeConfig() -> URL {
        let dir = Self.supportDir
        if !FileManager.default.fileExists(atPath: Self.sessionURL.path) {
            FileManager.default.createFile(atPath: Self.sessionURL.path, contents: nil)
        }
        // Keep the log from growing forever
        if let size = try? FileManager.default.attributesOfItem(atPath: Self.logURL.path)[.size] as? Int, size > 5_000_000 {
            try? FileManager.default.removeItem(at: Self.logURL)
        }

        var lines = [
            "# Generated by Swift DM on every launch — change settings in the app instead.",
            "enable-rpc=true",
            "rpc-listen-all=false",
            "rpc-listen-port=\(Prefs.rpcPort)",
            "rpc-secret=\(Prefs.secret)",
            "rpc-allow-origin-all=true",
            "rpc-max-request-size=64M",
            "input-file=\(Self.sessionURL.path)",
            "save-session=\(Self.sessionURL.path)",
            "save-session-interval=10",
            "force-save=false",
            "continue=false",
            "min-split-size=1M",
            "file-allocation=none",
            "disk-cache=8M",
            "auto-file-renaming=true",
            "allow-overwrite=false",
            "content-disposition-default-utf8=true",
            "max-tries=5",
            "retry-wait=5",
            "connect-timeout=30",
            "timeout=30",
            "http-accept-gzip=true",
            "listen-port=\(Prefs.btPort)",
            "dht-listen-port=\(Prefs.dhtPort)",
            "enable-dht=true",
            "enable-dht6=true",
            "dht-file-path=\(dir.appendingPathComponent("dht.dat").path)",
            "dht-file-path6=\(dir.appendingPathComponent("dht6.dat").path)",
            "bt-load-saved-metadata=true",
            "bt-max-peers=128",
            "bt-enable-lpd=true",
            "follow-torrent=true",
            "follow-metalink=true",
            "summary-interval=0",
            "console-log-level=warn",
            "log=\(Self.logURL.path)",
            "log-level=warn",
        ]
        for (k, v) in Prefs.liveOptions.sorted(by: { $0.key < $1.key }) where !v.isEmpty {
            lines.append("\(k)=\(v)")
        }
        try? (lines.joined(separator: "\n") + "\n").write(to: Self.confURL, atomically: true, encoding: .utf8)
        return Self.confURL
    }

    func start() {
        guard !isRunning else { return }
        guard let bin = binary else { lastError = "aria2c is missing from the app bundle."; return }
        let p = Process()
        p.executableURL = bin
        p.arguments = ["--conf-path=\(writeConfig().path)", "--stop-with-process=\(getpid())"]
        p.standardOutput = FileHandle.nullDevice
        p.standardError = FileHandle.nullDevice
        do {
            try p.run()
            process = p
            lastError = nil
        } catch {
            lastError = "Couldn't start aria2: \(error.localizedDescription)"
        }
    }

    func stop() {
        guard let p = process, p.isRunning else { process = nil; return }
        p.terminate() // SIGTERM → aria2 saves its session, then exits
        let deadline = Date().addingTimeInterval(4)
        while p.isRunning && Date() < deadline { usleep(50_000) }
        process = nil
    }

    func restart() {
        stop()
        start()
    }

    /// Clears the saved download list (used by "Reset session").
    func resetSession() {
        stop()
        try? Data().write(to: Self.sessionURL)
        start()
    }
}
